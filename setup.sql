-- EMS fresh-project setup (free Supabase plan)
-- Safe to re-run. Does not delete data. Never put service-role keys in the browser.
create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  purchase_date date not null default current_date,
  item_name text not null,
  quantity numeric not null check (quantity > 0),
  unit text not null default 'piece',
  amount numeric not null check (amount >= 0),
  category text not null default 'Other',
  source text,
  description text,
  created_at timestamptz not null default now(),
  spent_by text,
  order_id text,
  forecast_eligible boolean not null default false
);
alter table public.purchases add column if not exists forecast_eligible boolean not null default false;

create table if not exists public.item_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  usage_date date not null default current_date,
  item_name text not null,
  quantity numeric not null check (quantity > 0),
  unit text not null default 'piece',
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.family_members (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.shops (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);

alter table public.purchases enable row level security;
alter table public.item_usage enable row level security;
alter table public.family_members enable row level security;
alter table public.shops enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='purchases' and policyname='Users manage own purchases') then
    create policy "Users manage own purchases" on public.purchases for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='item_usage' and policyname='Users manage own item usage') then
    create policy "Users manage own item usage" on public.item_usage for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='family_members' and policyname='Users manage own family members') then
    create policy "Users manage own family members" on public.family_members for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='shops' and policyname='Users manage own shops') then
    create policy "Users manage own shops" on public.shops for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
end $$;

create index if not exists purchases_user_date_idx on public.purchases(user_id, purchase_date desc);
create index if not exists purchases_user_item_idx on public.purchases(user_id, item_name);
create index if not exists item_usage_user_date_idx on public.item_usage(user_id, usage_date desc);

comment on column public.purchases.forecast_eligible is
  'True only for purchases entered after forecasting launch; old historical purchases stay excluded from prediction training.';
