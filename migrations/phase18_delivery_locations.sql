
-- Saved delivery locations for household shopping plans.
create table if not exists public.delivery_locations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null check (length(trim(label)) between 1 and 60),
  address text not null check (length(trim(address)) between 3 and 500),
  city text,
  postal_code text,
  created_at timestamptz not null default now(),
  unique (user_id, label)
);
alter table public.delivery_locations enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='delivery_locations' and policyname='Users manage own delivery locations') then
    create policy "Users manage own delivery locations" on public.delivery_locations for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
end $$;
create index if not exists delivery_locations_user_label_idx on public.delivery_locations(user_id, label);
